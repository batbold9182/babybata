# Builds babybata.ipynb from your local files, so Colab gets the latest version.
# Run this again every time you edit data/babybata.txt or train.py:
#     python make_notebook.py
#
# Why: the notebook RUNS on Google's computer, which can't see files on your PC.
# So the notebook itself carries the data and code, and writes them over there.

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# Bump this every training round, so each version gets its own Drive folder.
VERSION = "v5"


def read(name):
    with open(os.path.join(HERE, name), encoding="utf-8") as f:
        return f.read()


def markdown(text):
    return {"cell_type": "markdown", "metadata": {}, "source": text.strip()}


def code(text):
    return {"cell_type": "code", "metadata": {}, "execution_count": None,
            "outputs": [], "source": text.strip()}


cells = [
    markdown("""
# BabyBata 🍼 fine-tuning GPT-2

Runs on a free Colab GPU. **Kernel → Colab → GPU (T4)**, then run the cells top to bottom.

⚠️ This notebook is generated by `make_notebook.py`. Edit `data/babybata.txt` or `train.py`, then regenerate it.
Don't edit the data cells here directly: your changes would be overwritten.
"""),
    markdown("## 1. Check the GPU"),
    code("""
import os
import torch

os.makedirs("data", exist_ok=True)
if torch.cuda.is_available():
    print("GPU ready:", torch.cuda.get_device_name(0))
else:
    print("No GPU! Pick a GPU runtime (T4). Training on CPU works but is slow.")
"""),
    markdown("## 2. Send the training data and code to the Colab machine"),
    code("%%writefile data/babybata.txt\n" + read(os.path.join("data", "babybata.txt"))),
    code("%%writefile data/generated.txt\n" + read(os.path.join("data", "generated.txt"))),
    code("%%writefile train.py\n" + read("train.py")),
    code("%%writefile facts.py\n" + read("facts.py")),
    code("%%writefile check.py\n" + read("check.py")),
    markdown("## 3. Train (~2-3 minutes on a T4)\nStarts from plain GPT-2 here (your laptop's v1 isn't on this machine)."),
    code("!python train.py"),
    markdown("## 3b. Fact check: how many of the 15 key facts does it get right?"),
    code("!python check.py"),
    markdown("## 4. Talk to BabyBata\nEdit the questions and re-run. `compare=True` also shows what plain GPT-2 says."),
    code("""
from transformers import GPT2LMHeadModel, GPT2TokenizerFast
from train import OUT_DIR, prompt_for
from facts import fill

device = "cuda" if torch.cuda.is_available() else "cpu"
tokenizer = GPT2TokenizerFast.from_pretrained(OUT_DIR)
babybata = GPT2LMHeadModel.from_pretrained(OUT_DIR).to(device).eval()
plain_gpt2 = None


def reply(model, question):
    ids = tokenizer.encode(prompt_for(question), return_tensors="pt").to(device)
    with torch.no_grad():
        out = model.generate(ids, attention_mask=torch.ones_like(ids), max_new_tokens=80,
                             do_sample=True, temperature=0.3, top_p=0.9, repetition_penalty=1.05,
                             pad_token_id=tokenizer.eos_token_id, eos_token_id=tokenizer.eos_token_id)
    text = tokenizer.decode(out[0][ids.shape[1]:], skip_special_tokens=True)
    return fill(text.split("\\nUser:")[0].strip())  # {EMAIL} -> the real email


def ask(question, compare=False):
    global plain_gpt2
    print("You:        ", question)
    print("BabyBata:   ", reply(babybata, question))
    if compare:
        if plain_gpt2 is None:
            plain_gpt2 = GPT2LMHeadModel.from_pretrained("gpt2").to(device).eval()
        print("plain GPT-2:", reply(plain_gpt2, question))
    print()


ask("Who are you?", compare=True)
ask("What kind of projects do you build?", compare=True)
ask("How do I get in touch?")
ask("What's his GitHub?")
ask("What's the best pizza topping?")
"""),
    markdown("""
## 5. Save BabyBata __VERSION__ to Google Drive
Saved as a NEW folder `babybata-model-__VERSION__`, so the old version on your Drive is kept.
If mounting fails, open the Command Palette (`Ctrl+Shift+P`) and run the Colab extension's **Mount Google Drive** command.
"""),
    code("""
from google.colab import drive

drive.mount("/content/drive")
!mkdir -p /content/drive/MyDrive/babybata/babybata-model-__VERSION__
!cp -r models/babybata-model/. /content/drive/MyDrive/babybata/babybata-model-__VERSION__/
print("Saved to Google Drive: MyDrive/babybata/babybata-model-__VERSION__")
"""),
    markdown("""
## 6. Compress BabyBata (optional, ~2 minutes)
Quantizes the weights to 8 and 4 bits (by hand), removes 6 of the 12 layers, and scores every version.
Needs step 3 to have run in this session.
"""),
    code("%%writefile compress.py\n" + read("compress.py")),
    code("!python compress.py"),
    markdown("## 7. Save the small model to Google Drive"),
    code("""
!mkdir -p /content/drive/MyDrive/babybata/babybata-model-small-__VERSION__
!cp -r models/babybata-model-small/. /content/drive/MyDrive/babybata/babybata-model-small-__VERSION__/
print("Saved to Google Drive: MyDrive/babybata/babybata-model-small-__VERSION__")
"""),
]

# put the version number into the Drive-saving cells
for cell in cells:
    cell["source"] = cell["source"].replace("__VERSION__", VERSION)

notebook = {
    "cells": cells,
    "metadata": {
        "accelerator": "GPU",
        "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
        "language_info": {"name": "python"},
    },
    "nbformat": 4,
    "nbformat_minor": 5,
}

with open(os.path.join(HERE, "babybata.ipynb"), "w", encoding="utf-8") as f:
    json.dump(notebook, f, indent=1, ensure_ascii=False)
print("Wrote babybata.ipynb. Open it in VS Code and select a Colab GPU kernel.")
